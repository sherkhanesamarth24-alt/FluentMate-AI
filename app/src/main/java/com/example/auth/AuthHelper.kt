@Composable
private fun AuthHeroArtwork(modifier: Modifier = Modifier) {
    val primary = MaterialTheme.colorScheme.primary
    val secondary = MaterialTheme.colorScheme.secondary
    val tertiary = MaterialTheme.colorScheme.tertiary
    val surface = MaterialTheme.colorScheme.surfaceVariant

    Card(
        shape = RoundedCornerShape(24.dp),
        colors = CardDefaults.cardColors(containerColor = surface),
        modifier = modifier
    ) {
        Box(modifier = Modifier.fillMaxSize()) {
            Canvas(modifier = Modifier.fillMaxSize()) {
                val w = size.width
                val h = size.height

                // Ambient glow circles
                drawCircle(
                    brush = Brush.radialGradient(
                        colors = listOf(primary.copy(alpha = 0.28f), Color.Transparent),
                        center = Offset(w * 0.25f, h * 0.35f),
                        radius = w * 0.4f
                    ),
                    radius = w * 0.4f,
                    center = Offset(w * 0.25f, h * 0.35f)
                )
                drawCircle(
                    brush = Brush.radialGradient(
                        colors = listOf(secondary.copy(alpha = 0.24f), Color.Transparent),
                        center = Offset(w * 0.78f, h * 0.65f),
                        radius = w * 0.38f
                    ),
                    radius = w * 0.38f,
                    center = Offset(w * 0.78f, h * 0.65f)
                )

                // Soundwave curve
                val wavePath = Path().apply {
                    moveTo(0f, h * 0.62f)
                    cubicTo(
                        w * 0.25f, h * 0.25f,
                        w * 0.45f, h * 0.90f,
                        w * 0.7f, h * 0.42f
                    )
                    cubicTo(
                        w * 0.85f, h * 0.18f,
                        w * 0.93f, h * 0.55f,
                        w, h * 0.45f
                    )
                }
                drawPath(
                    path = wavePath,
                    brush = Brush.horizontalGradient(listOf(primary, secondary, tertiary)),
                    style = Stroke(width = 6.dp.toPx(), cap = StrokeCap.Round)
                )

                // Secondary subtle wave
                val wavePath2 = Path().apply {
                    moveTo(0f, h * 0.74f)
                    cubicTo(
                        w * 0.3f, h * 0.48f,
                        w * 0.55f, h * 0.98f,
                        w, h * 0.6f
                    )
                }
                drawPath(
                    path = wavePath2,
                    color = primary.copy(alpha = 0.25f),
                    style = Stroke(width = 3.dp.toPx(), cap = StrokeCap.Round)
                )

                // Accent nodes
                drawCircle(color = primary, radius = 8.dp.toPx(), center = Offset(w * 0.32f, h * 0.48f))
                drawCircle(color = tertiary, radius = 6.dp.toPx(), center = Offset(w * 0.70f, h * 0.42f))
                drawCircle(color = secondary, radius = 7.dp.toPx(), center = Offset(w * 0.86f, h * 0.37f))
            }

            Column(
                modifier = Modifier
                    .align(Alignment.BottomStart)
                    .padding(18.dp)
            ) {
                Text(
                    text = "\"I went to college yesterday.\"",
                    style = MaterialTheme.typography.titleMedium,
                    color = MaterialTheme.colorScheme.onSurface
                )
                Text(
                    text = "Marathi Coach • Voice AI • Daily Streaks",
                    style = MaterialTheme.typography.labelMedium,
                    color = MaterialTheme.colorScheme.primary
                )
            }
        }
    }
}
